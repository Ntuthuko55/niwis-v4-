import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'

const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1820, height: 1120 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
let failSurface = false
await page.route('**/api/**', async route => {
  const url = new URL(route.request().url())
  if (url.pathname.startsWith('/niwis-api/')) return route.fulfill({ json: { predictions: [] } })
  if (url.pathname.includes('/drought-monitoring/')) return route.fulfill({ status: 503, json: { detail: 'Unrelated drought source excluded from test' } })
  if (failSurface && url.pathname === '/api/surface-water/dashboard') return route.fulfill({ status: 503, json: { detail: 'Surface-water source unavailable for test' } })
  try {
    const response = await route.fetch({ url: `http://127.0.0.1:8021${url.pathname.replace(/^\/api/, '')}${url.search}`, timeout: 120000 })
    await route.fulfill({ response })
  } catch { await route.abort() }
})
try {
  await page.goto('http://127.0.0.1:5179', { waitUntil: 'domcontentloaded' })
  await page.locator('.nw-nav').getByRole('button', { name: /Surface water network/ }).click()
  await page.getByRole('heading', { name: 'Surface Water Monitoring Network', exact: true }).waitFor()
  await page.getByRole('heading', { name: 'Catchment land cover', exact: true }).waitFor({ timeout: 120000 })
  assert.equal(await page.getByLabel('Surface water region').locator('option').count(), 53)
  assert.equal(await page.locator('.rf-kpi').count(), 6)
  assert.equal(await page.locator('.rf-map-panel .sat-district-map>svg>path').count(), 52)
  assert.equal(await page.locator('.rf-map-panel .sat-district-map>svg>path[fill="#254251"]').count(), 0, 'Historical district aliases must map to all current boundaries')
  assert.equal(await page.locator('.rf-map-panel .province-map-labels text').count(), 9)
  assert.equal(await page.getByLabel('Surface water end month').inputValue(), '2026-08')
  assert.ok((await page.locator('.sw-data-note').innerText()).includes('113,9'))
  assert.ok((await page.locator('.sw-profile-grid').innerText()).includes('Not supplied'))
  await page.getByText('Select a district to inspect its rating relationship', { exact: true }).waitFor()
  await page.getByRole('img', { name: 'Reported river discharge chart', exact: true }).waitFor()
  await mkdir('output', { recursive: true })
  await page.screenshot({ path: 'output/surface-water-desktop.png', fullPage: true })
  console.log('PASS three source datasets, 52 districts, nine province names, honest BFI and land-cover handling')

  await page.getByLabel('Surface water map indicator').selectOption('flood_extent')
  await page.getByLabel('Surface water hydrology indicator').selectOption('velocity')
  await page.getByRole('img', { name: 'Flow velocity chart', exact: true }).waitFor()
  await page.getByLabel('Surface water satellite indicator').selectOption('turbidity')
  await page.getByRole('img', { name: 'Turbidity proxy chart', exact: true }).waitFor()
  await page.getByLabel('Surface water sediment indicator').selectOption('sediment_total')
  await page.getByRole('img', { name: 'Observed sediment load chart', exact: true }).waitFor()
  await page.getByLabel('Surface water ranking').selectOption('water_extent')
  const district = await page.locator('.rf-ranking strong').first().innerText()
  await page.locator('.rf-ranking>button').first().click()
  await page.waitForFunction(name => document.querySelector('.rf-context')?.textContent.includes(name), district)
  assert.equal(await page.getByLabel('Surface water region').inputValue(), district)
  await page.getByRole('img', { name: 'Observed stage and discharge scatter', exact: true }).waitFor()
  console.log('PASS map layers, hydrology/EO/sediment selectors, district ranking and regional rating scatter')

  await page.getByLabel('Surface water region').selectOption('City of Tshwane')
  await page.getByLabel('Surface water start month').fill('2024-01')
  await page.getByLabel('Surface water end month').fill('2024-12')
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.rf-context')?.textContent.includes('City of Tshwane'))
  const monthlyDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export monthly data', exact: true }).click()
  const monthlyCSV = await readFile(await (await monthlyDownload).path(), 'utf8')
  assert.equal(monthlyCSV.trim().split('\r\n').length, 13)
  assert.ok(monthlyCSV.includes('Baseflow index (ratio)'))
  assert.ok(monthlyCSV.includes('Rainfall context (mm/month)'))
  const dailyResponse = page.waitForResponse(response => response.url().includes('/api/surface-water/daily?') && response.url().includes('month=2024-02'))
  await page.getByLabel('Surface water daily month').selectOption('2024-02')
  assert.equal((await (await dailyResponse).json()).series.length, 29)
  await page.getByRole('button', { name: 'Flow consistency', exact: true }).click()
  await page.getByRole('img', { name: 'Reported river discharge, Volume-equivalent mean flow chart', exact: true }).waitFor()
  const dailyDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Daily CSV', exact: true }).click()
  const dailyCSV = await readFile(await (await dailyDownload).path(), 'utf8')
  assert.equal(dailyCSV.trim().split('\r\n').length, 30)
  assert.ok(dailyCSV.includes('Daily flow volume (m³/day)'))
  await page.locator('.rf-register summary').click()
  await page.locator('.rf-register').getByRole('button', { name: 'Earth observation', exact: true }).click()
  assert.equal(await page.locator('.rf-register tbody tr').count(), 6)
  await page.locator('.rf-register summary').click()
  console.log('PASS region/date filters, monthly and leap-year daily exports, flow consistency view and all satellite indicators')

  await page.getByLabel('Surface water start month').fill('2026-09')
  await page.getByLabel('Surface water end month').fill('2026-09')
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  await page.locator('.rf-warning').waitFor()
  assert.ok((await page.locator('.rf-warning').innerText()).includes('Conflicting monthly-flow values are omitted'))
  assert.ok((await page.locator('.sw-quality-item').last().innerText()).includes('1'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: 'output/surface-water-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Surface-water mobile overflow')
  failSurface = true
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  await page.getByRole('alert').getByText('Surface-water source unavailable for test').waitFor()
  assert.equal(await page.locator('.rf-kpi').count(), 0)
  failSurface = false
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await page.locator('.rf-kpi').first().waitFor()
  console.log('PASS conflicting September data, mobile layout and source-error recovery')

  // Finish browser verification of the runoff module, whose earlier preview was blocked by approval quota.
  await page.setViewportSize({ width: 1820, height: 1120 })
  await page.locator('.nw-nav').getByRole('button', { name: /Runoff status/ }).click()
  await page.getByRole('heading', { name: 'Runoff Status Monitoring', exact: true }).waitFor()
  await page.getByRole('heading', { name: 'Flood return-period estimates', exact: true }).waitFor({ timeout: 120000 })
  assert.equal(await page.locator('.rf-kpi').count(), 6)
  assert.equal(await page.locator('.rf-map-panel .province-map-labels text').count(), 9)
  await page.getByLabel('Runoff catchment indicator').selectOption('response_time')
  await page.getByText('This variable is constant across every district and date in the source.', { exact: true }).waitFor()
  await page.getByRole('img', { name: 'Daily runoff chart', exact: true }).waitFor()
  const runoffDailyDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Daily CSV', exact: true }).click()
  const runoffCSV = await readFile(await (await runoffDailyDownload).path(), 'utf8')
  assert.equal(runoffCSV.trim().split('\r\n').length, 32)
  assert.ok(runoffCSV.includes('Daily runoff (m³/day)'))
  await page.screenshot({ path: 'output/runoff-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: 'output/runoff-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Runoff mobile overflow')
  assert.deepEqual(errors, [])
  console.log('PASS runoff preview, source attributes, daily export and mobile layout; no JavaScript errors in either module')
} finally {
  await browser.close()
}
